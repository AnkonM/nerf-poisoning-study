"""Phase 6 closeout summary: one row per run, per-condition mean/std, contact sheet.

Read-only over experiments/runs/ and experiments/results/results.csv. The only PSNR
here is evaluate.py's whole-frame mean over the 75 frozen eval views; it is NOT any
METHODOLOGY §6 metric.
"""

import csv
import json
import math
import os
import statistics
from typing import Dict, List, Optional

CONTROL_REFERENCE_DB = 50.778   # D-033/D-034: final-scene clean control at 200,000 iterations
OUTLIER_DB = 3.0


def load_events(run_dir: str) -> List[dict]:
    p = os.path.join(run_dir, "harness_events.jsonl")
    if not os.path.isfile(p):
        return []
    with open(p) as f:
        return [json.loads(line) for line in f if line.strip()]


def resume_retry_events(events: List[dict]) -> List[str]:
    """Human-readable 'kind@iteration' for every resume / retry event."""
    out = []
    for e in events:
        if e.get("event") in ("resume", "retry"):
            out.append("%s@%s" % (e["event"], e.get("from_iteration")))
    return out


def collect_rows(runs_dir: str, results_csv: str) -> List[dict]:
    with open(results_csv, newline="") as f:
        csv_rows = list(csv.DictReader(f))
    rows = []
    for r in csv_rows:
        run_dir = os.path.join(runs_dir, r["run_id"])
        with open(os.path.join(run_dir, "summary.json")) as f:
            summ = json.load(f)
        with open(os.path.join(run_dir, "eval_%s.json" % r["run_id"])) as f:
            ev = json.load(f)
        events = load_events(run_dir)
        rows.append({
            "run_id": r["run_id"], "condition": r["condition_id"], "seed": int(r["seed"]),
            "final_loss": float(summ["final_train_loss"]),
            "psnr": float(ev["test_psnr"]),
            "train_hours": float(summ["elapsed_hours"]),
            "csv_train_hours": float(r["train_wall_hours"]),
            "eval_minutes": float(ev["elapsed_minutes"]),
            "resume_events": int(r["resume_events"]), "retry_events": int(r["retry_events"]),
            "events": resume_retry_events(events),
            "resumed": bool(summ.get("resumed")),
        })
    return rows


def condition_stats(rows: List[dict]) -> Dict[str, dict]:
    by: Dict[str, List[float]] = {}
    for r in rows:
        by.setdefault(r["condition"], []).append(r["psnr"])
    return {c: {"n": len(v), "mean": statistics.mean(v),
                "std": statistics.stdev(v) if len(v) > 1 else float("nan")} for c, v in by.items()}


def outliers(rows: List[dict], limit_db: float = OUTLIER_DB) -> List[dict]:
    """Runs whose PSNR is more than `limit_db` outside the range of the same condition's OTHER seeds."""
    flagged = []
    for r in rows:
        others = [o["psnr"] for o in rows if o["condition"] == r["condition"] and o["seed"] != r["seed"]]
        if not others:
            continue
        lo, hi = min(others), max(others)
        dist = max(lo - r["psnr"], r["psnr"] - hi, 0.0)
        if dist > limit_db:
            flagged.append({"run_id": r["run_id"], "psnr": r["psnr"], "others": others, "outside_by_db": dist})
    return flagged


def render_markdown(rows: List[dict]) -> str:
    stats = condition_stats(rows)
    ref = next((r for r in rows if r["condition"] == "control" and r["seed"] == 1), None)
    out = ["# Phase 6 sweep summary (24 runs)", "",
           "Generated by `scripts/make_phase6_summary.py` from `experiments/runs/*` and `results.csv`.",
           "All PSNR here is **whole-frame PSNR from evaluate.py, NOT the §6 metrics** "
           "(no masked/unmasked PSNR/SSIM/LPIPS, no plate distance). Per D-034 these absolute values "
           "must not be compared with published NeRF numbers; interpret only relative to this scene's control.", "",
           "## Per run", "",
           "| run_id | condition | seed | final train loss | eval mean PSNR (dB) | train wall (h) | eval (min) "
           "| resume/retry events (kind@iteration) | resumed=true |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ev = ", ".join(r["events"]) if r["events"] else "none"
        out.append("| %s | %s | %d | %.3e | %.3f | %.2f | %.1f | %s (resume %d, retry %d) | %s |" % (
            r["run_id"], r["condition"], r["seed"], r["final_loss"], r["psnr"], r["train_hours"],
            r["eval_minutes"], ev, r["resume_events"], r["retry_events"], "YES" if r["resumed"] else "no"))
    out += ["", "## Per condition: whole-frame PSNR from evaluate.py, NOT the §6 metrics", "",
            "| condition | N | mean PSNR (dB) | sample std (dB) |", "|---|---|---|---|"]
    for c in sorted(stats, key=lambda c: (-1, 0) if c == "control" else (0, int(c[1:]))):
        s = stats[c]
        out.append("| %s | %d | %.3f | %.3f |" % (c, s["n"], s["mean"], s["std"]))
    out += ["", "## Sanity flags (reported, not judged)", ""]
    if ref:
        out.append("- control seed 1 PSNR %.3f dB vs reference %.3f dB (D-033/D-034, 200k probe): difference %+.3f dB."
                   % (ref["psnr"], CONTROL_REFERENCE_DB, ref["psnr"] - CONTROL_REFERENCE_DB))
    fl = outliers(rows)
    if fl:
        for f in fl:
            out.append("- **%s** %.3f dB is %.2f dB outside its condition's other seeds (%s)."
                       % (f["run_id"], f["psnr"], f["outside_by_db"], ", ".join("%.3f" % o for o in f["others"])))
    else:
        out.append("- No run is more than %.1f dB outside the range of its condition's other seeds." % OUTLIER_DB)
    return "\n".join(out) + "\n"


def contact_sheet(png_paths: List[str], labels: List[str], out_path: str, cols: int = 6, thumb_w: int = 640) -> None:
    from PIL import Image, ImageDraw
    thumbs = []
    for p in png_paths:
        im = Image.open(p).convert("RGB")
        h = int(round(im.height * thumb_w / im.width))
        thumbs.append(im.resize((thumb_w, h), Image.LANCZOS))
    th = max(t.height for t in thumbs)
    rows = math.ceil(len(thumbs) / cols)
    pad = 22
    sheet = Image.new("RGB", (cols * thumb_w, rows * (th + pad)), "white")
    d = ImageDraw.Draw(sheet)
    for i, (t, lab) in enumerate(zip(thumbs, labels)):
        x, y = (i % cols) * thumb_w, (i // cols) * (th + pad)
        d.text((x + 6, y + 5), lab, fill="black")
        sheet.paste(t, (x, y + pad))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    sheet.save(out_path)
