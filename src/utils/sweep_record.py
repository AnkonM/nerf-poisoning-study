"""Per-run record: experiments/logs/<run_id>.md (from docs/templates/EXPERIMENT_LOG_TEMPLATE.md),
a loss-curve PNG exported from TensorBoard, and the results.csv row.

Only values that were MEASURED are filled. Fields the harness cannot measure are
left explicitly blank ("(not measured)"), and the six METHODOLOGY §6 metrics that
scripts/evaluate.py does not compute are marked as such rather than invented.
The log entry is written BEFORE the results row, per the template's rule that
metrics are not allowed into results.csv until the entry exists.
"""

import hashlib
import json
import math
import os
import time
from typing import Dict

from utils import sweep_checks as chk
from utils import sweep_state as st

NOT_MEASURED = "(not measured)"
NOT_COMPUTED = "not computed — scripts/evaluate.py does not compute this (see D-040); Phase 8 computes it from the retained checkpoints"


def _sha256(path: str) -> str:
    if not os.path.exists(path):
        return NOT_MEASURED
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def export_loss_png(run_dir: str, out_png: str) -> bool:
    """Loss curve from the run's TensorBoard events (all event files in tb/)."""
    from tensorboard.backend.event_processing.event_accumulator import EventAccumulator
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    tb = os.path.join(run_dir, "tb")
    if not os.path.isdir(tb):
        return False
    ea = EventAccumulator(tb, size_guidance={"scalars": 0})
    ea.Reload()
    tags = ea.Tags()["scalars"]
    if "train/loss" not in tags:
        return False
    fig, ax = plt.subplots(1, 2 if "val/psnr_subset" in tags else 1, figsize=(10, 3.6), squeeze=False)
    ev = ea.Scalars("train/loss")
    ax[0][0].semilogy([e.step for e in ev], [max(e.value, 1e-12) for e in ev], lw=0.8)
    ax[0][0].set(title="train/loss (single-batch, noisy)", xlabel="iteration")
    if "val/psnr_subset" in tags:
        v = ea.Scalars("val/psnr_subset")
        ax[0][1].plot([e.step for e in v], [e.value for e in v], marker="o", ms=3)
        ax[0][1].set(title="val-subset PSNR (5 views, dB)", xlabel="iteration")
    fig.suptitle(os.path.basename(run_dir))
    fig.tight_layout()
    os.makedirs(os.path.dirname(out_png), exist_ok=True)
    fig.savefig(out_png, dpi=110)
    plt.close(fig)
    return True


def write_run_record(cfg, run, iterations: int, rd: str, ev: Dict, pf: Dict) -> None:
    paths = cfg.paths
    events = st.read_events(rd)
    starts = [e for e in events if e["event"] in ("start", "resume")]
    resumes = [e for e in events if e["event"] == "resume"]
    retries = [e for e in events if e["event"] == "retry"]
    wall_h = sum(e.get("wall_s", 0) for e in events if e["event"] == "attempt_end") / 3600
    summary = json.load(open(os.path.join(rd, "summary.json")))
    log_p = os.path.join(rd, "train.log")
    pts = chk.parse_loss_points(open(log_p)) if os.path.exists(log_p) else []   # absent if trained outside the harness
    health = chk.check_loss_health(pts, cfg.window, cfg.ratio)
    env = (starts[0].get("env") if starts else None) or pf.get("env") or {}
    commit = pf["commit"]
    rel = os.path.relpath(run.config_path, cfg.repo_root)
    config_shown = run.config_path if rel.startswith("..") else rel      # repo-relative when inside the repo
    eval_agg = next((d for n, ok, d in pf.get("checks", []) if n == "frozen eval set"), NOT_MEASURED)
    os.makedirs(paths.logs, exist_ok=True)
    png_name = "%s_loss.png" % run.run_id
    have_png = export_loss_png(rd, os.path.join(paths.logs, png_name))
    ips = chk.throughput(pts, recent=len(pts))
    anomalies = []
    for e in events:
        if e["event"] in ("resume", "retry", "restart_clean", "checkpoint_quarantined", "interrupted", "attempt_end"):
            if e["event"] == "attempt_end" and e.get("returncode") == 0:
                continue
            anomalies.append("%s %s: %s" % (e["utc"], e["event"], {k: v for k, v in e.items()
                                                                  if k not in ("t", "utc", "event", "env")}))
    log_rel = os.path.join("logs", "%s.md" % run.run_id)
    md = f"""# Experiment Log — {run.run_id}

*Auto-generated by the Phase 6 sweep harness (D-040) from measured values; blank = not measured.*

## Identification

- **Run ID:** {run.run_id}
- **Condition:** {run.condition_id} — budget {run.budget_percent}% of V_target, {run.attack_type}, {run.view_selection} selection
- **Seed:** {run.seed}
- **Config file path:** `{config_shown}`
- **Git commit hash:** {commit}
- **Date/time started:** {starts[0]["utc"] if starts else NOT_MEASURED}
- **Date/time finished:** {time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
- **Training wall time (sum of attempts):** {wall_h:.3f} h

## Environment

- **Where run:** local — native Ubuntu 24.04 HPC machine (D-038), host `{env.get("hostname", NOT_MEASURED)}`
- **GPU:** {env.get("gpu", NOT_MEASURED)} (driver {env.get("driver", NOT_MEASURED)}, persistence mode {env.get("persistence_mode", NOT_MEASURED)})
- **PyTorch / CUDA versions:** {env.get("torch", NOT_MEASURED)} / build {env.get("cuda_build", NOT_MEASURED)}
- **CPU governor:** {env.get("cpu_governor", NOT_MEASURED)}
- **Environment file used:** `uv.lock`, sha256 `{_sha256(os.path.join(cfg.repo_root, "uv.lock"))}`

## Data

- **Poisoned image set:** `{run.dataset_rel}/` — {summary.get("n_poisoned_verified", NOT_MEASURED)} of {summary.get("n_train_views", NOT_MEASURED)} views verified poisoned by content (expected {run.n_poisoned_expected}); train-set sha256 `{summary.get("train_set_sha256", NOT_MEASURED)}`
- **Manifest checksum:** `data/poisoned/MANIFEST.csv` sha256 `{_sha256(cfg.manifest_path)}`
- **Eval set used:** `data/blender_scenes/eval_holdout/` — {eval_agg} (checked immediately before this run)

## Training

- **Iterations/epochs:** {iterations} (batch {summary.get("batch_size", NOT_MEASURED)})
- **Final training loss:** {summary.get("final_train_loss", NOT_MEASURED)} (single batch; final train PSNR {summary.get("final_train_psnr", NOT_MEASURED)} dB)
- **Convergence check:** automated windowed check: **{health["status"].upper()}** — {health["detail"]}. Loss curve: `{png_name if have_png else NOT_MEASURED}`. Human inspection of the curve (required by the Phase 6 gate): **PENDING**
- **Average throughput over logged windows:** {("%.2f it/s" % ips) if ips else NOT_MEASURED}
- **Anomalies observed:** {"none" if not anomalies else ""}
{chr(10).join("  - " + a for a in anomalies)}
- **Resume events:** {len(resumes)}; **retry events:** {len(retries)}{" — a resumed run restores RNG state and is bit-equivalent to an uninterrupted one (D-039)" if resumes else ""}

## Metrics (computed by `scripts/evaluate.py`, not by hand)

| Metric | Value |
|---|---|
| Whole-frame mean PSNR over {ev.get("n_test_views")} frozen eval views (what evaluate.py computes) | {ev.get("test_psnr"):.4f} dB |
| Masked PSNR (target region) | {NOT_COMPUTED} |
| Masked SSIM (target region) | {NOT_COMPUTED} |
| Masked LPIPS (target region) | {NOT_COMPUTED} |
| Unmasked PSNR (non-target) | {NOT_COMPUTED} |
| Unmasked SSIM (non-target) | {NOT_COMPUTED} |
| Unmasked LPIPS (non-target) | {NOT_COMPUTED} |
| Distance to background_plate (target region) | {NOT_COMPUTED} |

## Notes

All checkpoints (every 25,000 iterations plus the final one) are retained under `runs/{run.run_id}/` so the METHODOLOGY §6 metrics can be computed later against the frozen eval set. Whole-frame PSNR is relative to this scene's own control only (D-034): never compare it with published NeRF numbers.
"""
    tmp = os.path.join(paths.logs, run.run_id + ".md.tmp")
    with open(tmp, "w") as f:
        f.write(md)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, os.path.join(paths.logs, run.run_id + ".md"))

    row = {
        "run_id": run.run_id, "condition_id": run.condition_id, "seed": run.seed,
        "budget_percent": run.budget_percent, "attack_type": run.attack_type,
        "view_selection": run.view_selection, "dataset_id": run.dataset_id,
        "n_poisoned_verified": summary.get("n_poisoned_verified"),
        "train_set_sha256": summary.get("train_set_sha256"), "config_path": config_shown,
        "git_commit": commit, "iterations": iterations,
        "final_checkpoint": os.path.join("runs", run.run_id, st.final_ckpt_name(iterations)),
        "eval_json": os.path.join("runs", run.run_id, "eval_%s.json" % run.run_id),
        "n_test_views": ev.get("n_test_views"), "test_psnr_mean_whole_frame_db": "%.6f" % ev["test_psnr"],
        "final_train_loss": summary.get("final_train_loss"), "final_train_psnr": summary.get("final_train_psnr"),
        "train_wall_hours": "%.4f" % wall_h, "eval_minutes": "%.2f" % ev.get("elapsed_minutes", float("nan")),
        "resume_events": len(resumes), "retry_events": len(retries), "log_entry": log_rel,
        "hardware": "%s | driver %s | torch %s" % (env.get("gpu"), env.get("driver"), env.get("torch")),
        "finished_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    st.append_results_row(paths.results_csv, row)
